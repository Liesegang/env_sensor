source = '''/* Generated by shared/protocol/generate.py; edit shared/protocol/env-sensor-v1.json. */
#include <env_telemetry.h>
#include <stdbool.h>
#include <string.h>
struct writer { uint8_t *bytes; size_t size; size_t capacity; bool failed; };
static void put(struct writer *w, uint64_t value, size_t width)
{
    if (w->size + width > w->capacity) { w->failed = true; return; }
    for (size_t i = 0; i < width; i++) { w->bytes[w->size++] = value >> (8 * i); }
}
size_t env_telemetry_encode(const struct env_telemetry_sample *sample, uint8_t *output, size_t capacity)
{
    if (!sample || !output || capacity < ENV_TELEMETRY_HEADER_SIZE || (sample->enabled_mask & ~0x7f)) { return 0; }
    struct writer w = { output, 0, capacity, false };
    uint16_t valid = 0;
'''
for sensor in schema["sensors"]:
    source += f'    if ((sample->enabled_mask & {1 << (sensor["id"]-1)}) && sample->{sensor["key"]}.error == 0) {{ valid |= {1 << (sensor["id"]-1)}; }}\n'
source += '''    put(&w, 'O', 1); put(&w, 'E', 1); put(&w, 1, 1); put(&w, ENV_TELEMETRY_HEADER_SIZE, 1);
    put(&w, 0, 2); put(&w, sample->enabled_mask, 2); put(&w, valid, 2); put(&w, 0, 2);
    put(&w, sample->sequence, 4); put(&w, sample->uptime_ms, 8);
'''
widths = {"u8": 1, "bool": 1, "u16": 2, "i16": 2, "u32": 4, "i32": 4, "u64": 8}
for sensor in schema["sensors"]:
    key = sensor["key"]
    size = 2 + sum(widths[f["type"]] for f in sensor["fields"])
    source += f'''    if (sample->enabled_mask & {1 << (sensor["id"]-1)}) {{
        if (sample->{key}.error > 0) {{ return 0; }}
        put(&w, {sensor["id"]}, 1); put(&w, {sensor.get("version", 1)}, 1);
        put(&w, sample->{key}.error == 0 ? {size} : 2, 2);
        put(&w, (uint16_t)sample->{key}.error, 2);
        if (sample->{key}.error == 0) {{
'''
    for field in sensor["fields"]:
        source += f'            put(&w, sample->{key}.value.{field["key"]}, {widths[field["type"]]});\n'
    source += '        }\n    }\n'
source += '''    if (w.failed || w.size > ENV_TELEMETRY_MAX_SIZE) { return 0; }
    output[4] = w.size; output[5] = w.size >> 8;
    return w.size;
}
size_t env_telemetry_fragment(const uint8_t *frame, size_t length, size_t offset, uint8_t *output, size_t capacity)
{
    if (!frame || !output || length < ENV_TELEMETRY_HEADER_SIZE || length > ENV_TELEMETRY_MAX_SIZE || offset >= length || capacity <= ENV_TELEMETRY_FRAGMENT_HEADER_SIZE) { return 0; }
    struct writer w = { output, 0, capacity, false };
    put(&w, 'O', 1); put(&w, 'F', 1); put(&w, 1, 1); put(&w, 0, 1);
    memcpy(output + 4, frame + 12, 4); w.size += 4;
    put(&w, length, 2); put(&w, offset, 2);
    size_t count = length - offset;
    if (count > capacity - w.size) { count = capacity - w.size; }
    memcpy(output + w.size, frame + offset, count);
    return w.size + count;
}
'''

