#!/usr/bin/env python3
"""Generate shared history wire constants. JSON is the source of offsets."""
import argparse
import json
from pathlib import Path
import re
import sys


def camel(name):
    words = name.split("_")
    return words[0] + "".join(word.title() for word in words[1:])


def clock_outputs(root, widths):
    schema = json.loads(Path(__file__).with_name("env-clock-v1.json").read_text())
    c = ["/* Generated by shared/protocol/generate_history.py; do not edit. */",
         "#ifndef ENV_CLOCK_SCHEMA_H_", "#define ENV_CLOCK_SCHEMA_H_", "", "#include <stdint.h>", "",
         f"#define ENV_CLOCK_VERSION {schema['version']}U",
         f"#define ENV_CLOCK_FLAG_KNOWN {schema['flags']['known']}U",
         f"#define ENV_CLOCK_UTC_MINIMUM_MS UINT64_C({schema['utcMinimumMs']})",
         f"#define ENV_CLOCK_UTC_MAXIMUM_MS UINT64_C({schema['utcMaximumMs']})"]
    swift = ["// Generated by shared/protocol/generate_history.py; do not edit.",
             "public enum GeneratedClockSchema {",
             f"    public static let version: UInt8 = {schema['version']}",
             f"    public static let knownFlag: UInt8 = {schema['flags']['known']}",
             f"    public static let utcMinimumMs: UInt64 = {schema['utcMinimumMs']}",
             f"    public static let utcMaximumMs: UInt64 = {schema['utcMaximumMs']}"]
    for key in ["serviceUuid", "writeUuid", "stateUuid"]:
        ckey = re.sub(r"(?<!^)(?=[A-Z])", "_", key).upper()
        c.append(f"#define ENV_CLOCK_{ckey} \"{schema[key]}\"")
        swift.append(f"    public static let {key} = \"{schema[key]}\"")
    for name, format_ in schema["formats"].items():
        offset = 2
        c.extend(["", f"#define ENV_CLOCK_{name.upper()}_SIZE {format_['size']}U"])
        swift.extend([f"    public enum {name.title()} {{", f"        public static let size = {format_['size']}"])
        for at, byte in enumerate(format_["magic"].encode("ascii")):
            c.append(f"#define ENV_CLOCK_{name.upper()}_MAGIC_{at} 0x{byte:02x}U")
        swift.append("        public static let magic: [UInt8] = [" + ", ".join(f"0x{b:02x}" for b in format_["magic"].encode("ascii")) + "]")
        for field in format_["fields"]:
            assert field["offset"] == offset, f"clock {name}.{field['name']} layout hole/overlap"
            offset += widths[field["type"]]
            c.append(f"#define ENV_CLOCK_{name.upper()}_{field['name'].upper()}_OFFSET {field['offset']}U")
            swift.append(f"        public static let {camel(field['name'])} = {field['offset']}")
        assert offset == format_["size"], f"clock {name} size mismatch"
        swift.append("    }")
    c.extend(["", "#endif", ""])
    swift.extend(["}", ""])
    return {
        root / "shared/firmware/history/include/env_clock_schema.h": "\n".join(c),
        root / "card/software/EnvSensor/Protocol/GeneratedClockSchema.swift": "\n".join(swift),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    schema = json.loads(Path(__file__).with_name("env-history-v1.json").read_text())
    widths = {"u8": 1, "u16": 2, "i16": 2, "u32": 4, "i32": 4, "u64": 8}
    for name, format_ in schema["formats"].items():
        offset = 2 if "magic" in format_ else 0
        for field in format_["fields"]:
            assert field["offset"] == offset, f"{name}.{field['name']} layout hole/overlap"
            offset += widths[field["type"]]
        assert offset == format_["size"], f"{name} size mismatch"
    assert schema["formats"]["page"]["size"] + schema["maxRecords"] * schema["formats"]["record"]["size"] == schema["maxPageSize"]
    assert schema["maxPageSize"] <= 512
    c = ["/* Generated by shared/protocol/generate_history.py; do not edit. */",
         "#ifndef ENV_HISTORY_SCHEMA_H_", "#define ENV_HISTORY_SCHEMA_H_", "", "#include <stdint.h>", "",
         f"#define ENV_HISTORY_VERSION {schema['version']}U",
         f"#define ENV_HISTORY_MAX_RECORDS {schema['maxRecords']}U",
         f"#define ENV_HISTORY_MAX_PAGE_SIZE {schema['maxPageSize']}U"]
    swift = ["// Generated by shared/protocol/generate_history.py; do not edit.",
             "public enum GeneratedHistorySchema {",
             f"    public static let version: UInt8 = {schema['version']}",
             f"    public static let maxRecords = {schema['maxRecords']}",
             f"    public static let maxPageSize = {schema['maxPageSize']}"]
    for key in ["serviceUuid", "controlUuid", "statusUuid", "dataUuid"]:
        ckey = re.sub(r"(?<!^)(?=[A-Z])", "_", key).upper()
        c.append(f"#define ENV_HISTORY_{ckey} \"{schema[key]}\"")
        swift.append(f"    public static let {key} = \"{schema[key]}\"")
    for group, prefix in [("operations", "OP"), ("states", "STATE"), ("flags", "FLAG"), ("validity", "VALID"), ("rhtSources", "RHT")]:
        c.append("")
        swift.append(f"    public enum {group[0].upper() + group[1:]} {{")
        type_ = "UInt16" if group == "validity" else "UInt8"
        for key, value in schema[group].items():
            c.append(f"#define ENV_HISTORY_{prefix}_{key.upper()} {value}U")
            swift.append(f"        public static let {camel(key)}: {type_} = {value}")
        swift.append("    }")
    c.extend(["", f"#define ENV_HISTORY_UTC_MINIMUM UINT64_C({schema['utcRange']['minimum']})",
              f"#define ENV_HISTORY_UTC_MAXIMUM UINT64_C({schema['utcRange']['maximum']})"])
    swift.extend([f"    public static let utcMinimum: UInt64 = {schema['utcRange']['minimum']}",
                  f"    public static let utcMaximum: UInt64 = {schema['utcRange']['maximum']}"])
    for name, format_ in schema["formats"].items():
        c.extend(["", f"#define ENV_HISTORY_{name.upper()}_SIZE {format_['size']}U"])
        swift.append(f"    public enum {name.title()} {{")
        swift.append(f"        public static let size = {format_['size']}")
        if "magic" in format_:
            for at, byte in enumerate(format_["magic"].encode("ascii")):
                c.append(f"#define ENV_HISTORY_{name.upper()}_MAGIC_{at} 0x{byte:02x}U")
            swift.append("        public static let magic: [UInt8] = [" + ", ".join(f"0x{b:02x}" for b in format_["magic"].encode("ascii")) + "]")
        for field in format_["fields"]:
            c.append(f"#define ENV_HISTORY_{name.upper()}_{field['name'].upper()}_OFFSET {field['offset']}U")
            swift.append(f"        public static let {camel(field['name'])} = {field['offset']}")
        swift.append("    }")
    c.extend(["", "#endif", ""])
    swift.extend(["}", ""])
    targets = {
        root / "shared/firmware/history/include/env_history_schema.h": "\n".join(c),
        root / "card/software/EnvSensor/Protocol/GeneratedHistorySchema.swift": "\n".join(swift),
    }
    targets.update(clock_outputs(root, widths))
    stale = []
    for path, contents in targets.items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                stale.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    if stale:
        print("Stale history schema: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("History schema checked" if args.check else "History schema generated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
